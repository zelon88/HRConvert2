// / -----------------------------------------------------------------------------------
// / THE INTERFACE HELPER. ONE OBJECT. EVERY OPERATION GOES THROUGH IT.
// / A page calls configure() once with the values only PHP knows, then binds its controls.
// / Nothing in here reads the document for configuration & nothing is interpolated by PHP.
window.HRC2 = {

  // / Values supplied by the page through configure(). The defaults exist so that a
  // / method called before configure() reports a clear fault instead of dereferencing
  // / undefined.
  tokens: { Token1: '', Token2: '' },
  dataPath: '',
  shareBaseURL: '',
  sessionFiles: [],
  failureText: 'Operation Failed!',
  scanFailureText: 'Operation Failed!',
  operationFailedText: 'Operation Failed!',
  clipboardUnsupportedText: '',
  failureStrings: [],
  // / Where startOver() lands once the old session has been emptied. The page supplies it
  // / carrying the interface, language & colour, so a new session keeps the settings the
  // / user chose. The bare default is a last resort for a page that forgets to set it.
  newSessionURL: 'convertCore.php',
  // / Where refreshFileList() fetches the file list from. The page supplies it for the
  // / same reason. A fragment is rendered by a SEPARATE request, & a request that names
  // / no interface, language or colour is answered with the configured defaults. The list
  // / then comes back in the wrong language & the wrong colours, inside a page that is
  // / using the ones the user picked. The bare default is a last resort.
  fileListURL: 'convertCore.php?showFiles=1&fileListOnly=1',
  isConfigured: false,

  // / Accept the page's values. Every key is optional so a page supplies only what it uses.
  // / The upload page has no jQuery & no file list, & supplies neither.
  configure: function (settings) {
    var key = '';
    if (!settings) return false;
    for (key in settings) { if (settings.hasOwnProperty(key)) this[key] = settings[key]; }
    this.isConfigured = true;
    return true;
  },

  // / Somewhere to put a note that is worth recording & not worth interrupting for.
  warn: function (messageText) { warningToConsole(messageText); },

  // / Flip an element without letting a missing element throw.
  toggle: function (elementId) { toggle_visibility(elementId); },

  // / Whether one line of a core reply names a file.
  isFilename: function (line) { return line_is_filename(line); },

  // / Whether a core reply reports a failure, tested against this page's alert strings.
  isError: function (replyText) { return reply_is_error(replyText, this.failureStrings); },

  // / Point the hidden anchor at a file & report whether it did.
  download: function (basePath, fileName) { return download_file(basePath, fileName); },

  // / Show a banner & hide it again. The five second life is unchanged.
  flash: function (elementId) {
    var self = this;
    if (!document.getElementById(elementId)) return;
    self.toggle(elementId);
    window.setTimeout(function () { self.toggle(elementId); }, 5000);
  },

  // / Show or hide the spinner, without toggling it into the wrong state.
  // / toggle_visibility flips whatever it finds, so an operation that failed early could
  // / leave a spinner running forever. This asks for a state.
  spinner: function (elementId, shouldShow) {
    var element = document.getElementById(elementId);
    if (!element) return;
    var isVisible = (element.style.display !== 'none' && element.style.display !== '');
    if (isVisible !== shouldShow) this.toggle(elementId);
  },

  // / Read a form value by element id, safely.
  // / A missing element returned undefined & was posted as the string "undefined".
  value: function (elementId) {
    var element = document.getElementById(elementId);
    return element ? element.value : '';
  },

  // / Whether a checkbox is ticked. A missing checkbox is not ticked.
  checked: function (elementId) {
    var element = document.getElementById(elementId);
    return element ? !!element.checked : false;
  },

  // / One POST. Returns a promise so callers read top to bottom.
  post: function (payload) {
    var data = { Token1: this.tokens.Token1, Token2: this.tokens.Token2 };
    var key = '';
    for (key in payload) { if (payload.hasOwnProperty(key)) data[key] = payload[key]; }
    return $.ajax({ type: 'POST', url: 'convertCore.php', data: data });
  },

  // / The core reply is markup wrapped around one filename per line.
  // / A failure is collected rather than alerted immediately, so a batch reports once
  // / instead of once per file.
  // /
  // / EVERY LINE IS CLASSIFIED. NOTHING IS ACCEPTED BY POSITION.
  // / An earlier version discarded line one & treated every remaining line as a filename.
  // / Line one is the doctype, so that much worked, but an error message is followed by a
  // / line break & THAT was collected as a filename. A failed conversion then asked the
  // / core to download it & pointed the download anchor at the text of an error message.
  parseReply: function (replyText) {
    var self = this;
    var lines = String(replyText || '').split(/\r?\n/);
    var result = { files: [], errors: [] };
    lines.forEach(function (line) {
      line = line.trim();
      if (line === '') return;
      // / A tagged error, or an untagged refusal. Both are failures.
      if (self.isError(line)) { result.errors.push(line); return; }
      // / Anything left that cannot be a filename is markup around the answer.
      if (!self.isFilename(line)) return;
      result.files.push(line);
    });
    return result;
  },

  // / Ask for one file & hand it to the browser. Sequential by design.
  // / Ten parallel download requests raced each other & the core answered them in whatever
  // / order it finished, which is how a batch delivered the wrong file for the wrong row.
  downloadOne: function (fileName) {
    var self = this;
    return this.post({ download: fileName }).then(function (replyText) {
      // / The core answers a failed download with an HTTP 200 & an error in the body, so
      // / the body is the only thing that reports one. An empty body is NOT a failure
      // / here. A successful download prints nothing at all.
      if (self.isError(replyText)) return $.Deferred().reject(fileName).promise();
      if (!self.download(self.dataPath, fileName)) return $.Deferred().reject(fileName).promise();
      return fileName;
    });
  },

  downloadAll: function (fileNames) {
    var self = this;
    var chain = $.Deferred().resolve().promise();
    var failed = [];
    fileNames.forEach(function (fileName) {
      chain = chain.then(function () {
        return self.downloadOne(fileName).then(null, function () {
          failed.push(fileName);
          return $.Deferred().resolve().promise();
        });
      });
    });
    return chain.then(function () { return failed; });
  },

  // / Reload the file list without reloading the page.
  // / convertCore.php?showFiles=1&fileListOnly=1 already renders exactly this view, so the
  // / list needs nothing new from the core.
  // / .html rather than innerHTML, because the per file panels carry script blocks that
  // / bind their own click handlers & innerHTML never runs them.
  refreshFileList: function () {
    var self = this;
    var container = $('#hrc2FileList');
    if (container.length === 0) return;
    $.ajax({
      type: 'POST',
      url: this.fileListURL,
      data: { Token1: this.tokens.Token1, Token2: this.tokens.Token2 }
    }).then(function (returnedHtml) {
      try { container.html(returnedHtml); }
      catch (thrown) { self.warn('The file list could not be replaced. ' + thrown); }
    }, function () {
      // / A list that could not be refreshed is not worth an alert. The files are still
      // / there & the next conversion will try again.
      self.warn('The file list could not be refreshed.');
    });
  },

  // / THE WHOLE PATTERN, ONCE.
  // / suffix is the ConvertGuiCounter1 value, or an empty string for the bulk controls at
  // / the top of the page. Every element id is derived from it.
  run: function (payload, suffix) {
    var self = this;
    suffix = (suffix === undefined || suffix === null) ? '' : String(suffix);
    var loadingId = 'loadingCommandDiv' + suffix;
    var victoryId = 'victoryCommandDiv' + suffix;
    var failureId = 'failureCommandDiv' + suffix;
    var isFinished = false;

    // / THE SPINNER IS STOPPED HERE & NOWHERE ELSE.
    // / Every exit from this operation goes through this function, including the ones that
    // / were not planned for. A spinner that never stops is the worst outcome available,
    // / because it tells the user the work is still happening & gives them nothing to
    // / report. The guard makes it safe to call twice.
    var finish = function (problems, anySucceeded) {
      if (isFinished) return;
      isFinished = true;
      self.spinner(loadingId, false);
      if (problems && problems.length > 0) {
        self.flash(failureId);
        window.alert(problems.join('\n')); }
      if (anySucceeded) self.flash(victoryId);
      try { self.refreshFileList(); }
      catch (thrown) { self.warn('The file list could not be refreshed. ' + thrown); }
    };

    self.spinner(loadingId, true);

    self.post(payload).then(function (replyText) {
      // / EVERYTHING FROM HERE DOWN RUNS INSIDE A PROMISE HANDLER.
      // / jQuery catches whatever is thrown in one of these & converts the promise to a
      // / rejected one rather than letting it reach the console. Nothing downstream
      // / handles that rejection, so an uncaught throw in here is invisible & strands the
      // / operation. It is caught here instead.
      try {
        var parsed = self.parseReply(replyText);
        // / Nothing came back at all. The operation ran & produced no file.
        if (parsed.files.length === 0 && parsed.errors.length === 0) {
          finish([self.failureText], false);
          return; }
        // / A failure with no file to fetch is reported without asking the core for
        // / anything further. There is nothing to download.
        if (parsed.files.length === 0) {
          finish(parsed.errors, false);
          return; }
        self.downloadAll(parsed.files).then(function (failedDownloads) {
          try {
            var problems = parsed.errors.concat(failedDownloads.map(function (name) {
              return name + ' could not be downloaded.'; }));
            finish(problems, parsed.files.length > failedDownloads.length); }
          catch (thrown) {
            self.warn('Failed while reporting the result of an operation. ' + thrown);
            finish([self.failureText], false); }
        }, function (thrown) {
          // / downloadAll resolves even when every file fails, so reaching this arm means
          // / the chain itself broke rather than a download.
          self.warn('The download chain failed. ' + thrown);
          finish(parsed.errors.concat([self.failureText]), false); });
      }
      catch (thrown) {
        self.warn('Failed while reading the reply from the core. ' + thrown);
        finish([self.failureText], false); }
    }, function () {
      // / The request itself failed. There is no reply to read.
      finish([self.failureText], false);
    });
  },

  // / -------------------------------------------------------------------------------
  // / CONTROL BINDINGS.
  // / Each of these attaches one behaviour to one control. The page supplies the element
  // / ids & the values, & holds no behaviour of its own.
  // / Every binding waits for the document, because a per file panel is injected into a
  // / page that is already loaded & jQuery runs a ready handler immediately in that case.
  // / -------------------------------------------------------------------------------

  // / Bind a conversion control. staticPayload carries values PHP already knows, such as
  // / the input filename. fieldMap maps a POST name to the id of the input holding it, &
  // / is read at click time so the user's latest choice is the one that is sent.
  bindRun: function (buttonId, suffix, staticPayload, fieldMap) {
    var self = this;
    $(function () {
      $('#' + buttonId).click(function () {
        var payload = {};
        var key = '';
        for (key in staticPayload) { if (staticPayload.hasOwnProperty(key)) payload[key] = staticPayload[key]; }
        for (key in fieldMap) { if (fieldMap.hasOwnProperty(key)) payload[key] = self.value(fieldMap[key]); }
        self.run(payload, suffix);
      });
    });
  },

  // / Bind the per file download control.
  bindDownload: function (buttonId, suffix, fileName) {
    var self = this;
    $(function () {
      $('#' + buttonId).click(function () {
        self.spinner('loadingCommandDiv' + suffix, true);
        self.post({ download: fileName }).then(function (replyText) {
          self.spinner('loadingCommandDiv' + suffix, false);
          if (self.isError(replyText) || !self.download(self.dataPath, fileName)) {
            self.flash('failureCommandDiv' + suffix);
            window.alert(self.failureText);
            return; }
          self.flash('victoryCommandDiv' + suffix);
        }, function () {
          self.spinner('loadingCommandDiv' + suffix, false);
          self.flash('failureCommandDiv' + suffix);
          window.alert(self.failureText);
        });
      });
    });
  },

  // / Bind the per file delete confirmation control.
  // / The list is refreshed in place rather than reloading the document, because the list
  // / is fetched into the page & a reload would close every panel the user had open.
  bindDelete: function (buttonId, suffix, fileName) {
    var self = this;
    $(function () {
      $('#' + buttonId).click(function () {
        self.spinner('loadingCommandDiv' + suffix, true);
        self.post({ filesToDelete: fileName }).then(function (replyText) {
          self.spinner('loadingCommandDiv' + suffix, false);
          if (self.isError(replyText)) {
            self.flash('failureCommandDiv' + suffix);
            window.alert(self.operationFailedText);
            return; }
          self.flash('victoryCommandDiv' + suffix);
          self.refreshFileList();
        }, function () {
          self.spinner('loadingCommandDiv' + suffix, false);
          self.flash('failureCommandDiv' + suffix);
          window.alert(self.operationFailedText);
        });
      });
    });
  },

  // / Bind the two share controls for one file.
  // / A SHARE LINK FOR A FILE THE CORE REFUSED IS A LINK TO NOTHING.
  // / The reply is tested before anything is written to the page or the clipboard, because
  // / a user who is handed a dead URL has no reason to believe it is broken.
  bindShare: function (spec) {
    var self = this;
    var suffix = spec.suffix;
    var shareURL = share_file_url(spec.shareBaseURL, spec.fileName);
    var announce = function (copyToClipboard) {
      var linkStatus = document.getElementById('sharelinkStatus' + suffix);
      var clipStatus = document.getElementById('shareclipStatus' + suffix);
      var linkURL = document.getElementById('sharelinkURL' + suffix);
      if (linkStatus) linkStatus.innerHTML = spec.linkGeneratedHtml;
      if (linkURL) linkURL.innerHTML = spec.linkUrlPrefixHtml + '<i>' + shareURL + '</i>';
      if (copyToClipboard) {
        if (clipStatus) clipStatus.innerHTML = spec.clipCopiedHtml;
        copy_share_link(shareURL, self.clipboardUnsupportedText);
        window.alert(spec.copiedText); }
    };
    var request = function (copyToClipboard) {
      self.spinner('loadingCommandDiv' + suffix, true);
      self.post({ download: spec.fileName }).then(function (replyText) {
        self.spinner('loadingCommandDiv' + suffix, false);
        if (self.isError(replyText)) {
          self.flash('failureCommandDiv' + suffix);
          window.alert(self.operationFailedText);
          return; }
        announce(copyToClipboard);
        self.flash('victoryCommandDiv' + suffix);
      }, function () {
        self.spinner('loadingCommandDiv' + suffix, false);
        self.flash('failureCommandDiv' + suffix);
        window.alert(self.operationFailedText);
      });
    };
    $(function () {
      $('#' + spec.generateId).click(function () { request(true); });
      $('#' + spec.copyId).click(function () { request(false); });
    });
  },

  // / Scan a selection of files & then fetch the log the scan wrote.
  // / Both legs are tested. The scan can fail with an HTTP 200 & an error in the body, &
  // / without testing it the interface went on to ask for a log that was never written.
  scanThenFetchLog: function (scanType, fileNames, logFileName, suffix) {
    var self = this;
    var loadingId = 'loadingCommandDiv' + suffix;
    self.spinner(loadingId, true);
    self.post({ scantype: scanType, filesToScan: fileNames }).then(function (replyText) {
      if (self.isError(replyText)) {
        self.spinner(loadingId, false);
        self.flash('failureCommandDiv' + suffix);
        window.alert(self.scanFailureText);
        return; }
      self.post({ download: logFileName }).then(function (logReply) {
        self.spinner(loadingId, false);
        if (self.isError(logReply) || !self.download(self.dataPath, logFileName)) {
          self.flash('failureCommandDiv' + suffix);
          window.alert(self.scanFailureText);
          return; }
        self.flash('victoryCommandDiv' + suffix);
      }, function () {
        self.spinner(loadingId, false);
        self.flash('failureCommandDiv' + suffix);
        window.alert(self.scanFailureText);
      });
    }, function () {
      self.spinner(loadingId, false);
      self.flash('failureCommandDiv' + suffix);
      window.alert(self.scanFailureText);
    });
  },

  // / Bind one virus scan control with a fixed scanner.
  bindScan: function (buttonId, suffix, scanType, fileNames, logFileName) {
    var self = this;
    $(function () {
      $('#' + buttonId).click(function () {
        self.scanThenFetchLog(scanType, fileNames, logFileName, suffix);
      });
    });
  },

  // / Bind the bulk virus scan control, whose scanner is chosen by two checkboxes.
  // / Neither ticked is treated as both, because a scan button that does nothing at all
  // / reads as a broken control rather than as a refused one.
  bindScanAll: function (buttonId, suffix, clamCheckboxId, scanCoreCheckboxId, fileNames, logFileName) {
    var self = this;
    $(function () {
      $('#' + buttonId).click(function () {
        var useClam = self.checked(clamCheckboxId);
        var useScanCore = self.checked(scanCoreCheckboxId);
        var scanType = 'all';
        if (useClam && !useScanCore) scanType = 'clamav';
        if (useScanCore && !useClam) scanType = 'scancore';
        self.scanThenFetchLog(scanType, fileNames, logFileName, suffix);
      });
    });
  },

  // / Bind the bulk archive control. Archives every file in the session, then downloads
  // / the archive that was produced.
  bindArchiveAll: function (buttonId, suffix, fileNames, nameFieldId, extensionFieldId, defaultExtension) {
    var self = this;
    $(function () {
      $('#' + buttonId).click(function () {
        var loadingId = 'loadingCommandDiv' + suffix;
        var extension = self.value(extensionFieldId);
        var userFilename = self.value(nameFieldId);
        var archiveName = '';
        if (extension === '') extension = defaultExtension;
        archiveName = userFilename + '.' + extension;
        self.spinner(loadingId, true);
        self.post({ archive: '1', filesToArchive: fileNames, archextension: extension, userfilename: userFilename })
          .then(function (replyText) {
            if (self.isError(replyText)) {
              self.spinner(loadingId, false);
              self.flash('failureCommandDiv' + suffix);
              window.alert(self.failureText);
              return; }
            self.post({ download: archiveName }).then(function (downloadReply) {
              self.spinner(loadingId, false);
              if (self.isError(downloadReply) || !self.download(self.dataPath, archiveName)) {
                self.flash('failureCommandDiv' + suffix);
                window.alert(self.failureText);
                return; }
              self.flash('victoryCommandDiv' + suffix);
            }, function () {
              self.spinner(loadingId, false);
              self.flash('failureCommandDiv' + suffix);
              window.alert(self.failureText);
            });
          }, function () {
            // / THE ARCHIVE REQUEST ONCE HAD NO FAILURE HANDLER AT ALL.
            // / A transport failure left the spinner running for as long as the page
            // / stayed open & told the user nothing.
            self.spinner(loadingId, false);
            self.flash('failureCommandDiv' + suffix);
            window.alert(self.failureText);
          });
      });
    });
  },

  // / Delete every file in this session & then land on a new one.
  // / Deliberately plain XMLHttpRequest. The upload page does not load jQuery, & pulling a
  // / library in for one request would be a much larger change than the feature it serves.
  // /
  // / DELETING FIRST IS THE WHOLE POINT.
  // / Simply asking the core for a token free page would issue a new session & leave the
  // / previous one on disk, still served from its own path, until the deletion age
  // / threshold in config.php expires it. On an unauthenticated converter that is worse
  // / than offering nothing, because it LOOKS like it cleared something.
  startOver: function () {
    var self = this;
    var requestBody = 'Token1=' + encodeURIComponent(self.tokens.Token1)
                    + '&Token2=' + encodeURIComponent(self.tokens.Token2);
    var request = new XMLHttpRequest();
    var index = 0;
    // / filesToDelete[] repeated once per file is what PHP reads back as an array.
    for (index = 0; index < self.sessionFiles.length; index++)
      requestBody += '&filesToDelete%5B%5D=' + encodeURIComponent(self.sessionFiles[index]);
    request.open('POST', 'convertCore.php', true);
    request.setRequestHeader('Content-Type', 'application/x-www-form-urlencoded');
    request.onload = function () {
      // / A failed delete must NOT go on to issue a new session. Doing that would abandon
      // / the very files this control promised to remove.
      if (self.isError(request.responseText)) { window.alert(self.operationFailedText); return; }
      // / A request carrying no tokens is what makes the core issue a new session.
      // / The URL still carries the interface, language & colour, because a user who
      // / clears their files has not asked to be moved to a different interface in a
      // / different language. Only the session is meant to be new.
      window.location.href = self.newSessionURL;
    };
    request.onerror = function () { window.alert(self.operationFailedText); };
    request.send(requestBody);
  },

  // / Bind the start over confirmation control on the upload page.
  // / No jQuery here, because the upload page does not load it.
  bindStartOver: function (buttonId) {
    var self = this;
    var element = document.getElementById(buttonId);
    if (!element) return;
    element.onclick = function () { self.startOver(); return false; };
  },

  // / Called once when the document is ready. This is what loads the list.
  init: function () {
    if (document.getElementById('hrc2FileList')) this.refreshFileList();
  }
};
