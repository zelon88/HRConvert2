  spinner: function (elementId, shouldShow) {
    var element = document.getElementById(elementId);
    if (!element) return;
    var isVisible = (element.style.display !== 'none' && element.style.display !== '');
    if (isVisible !== shouldShow) this.toggle(elementId);
  },

