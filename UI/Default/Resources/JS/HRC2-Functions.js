// / -----------------------------------------------------------------------------------
// / A function to record a note that is worth keeping & is not worth interrupting a user for.
// / Defined first because the functions below report through it.
function warningToConsole(messageText) {
  if (window.console && window.console.warn) window.console.warn('HRConvert2. ' + messageText); }
// / -----------------------------------------------------------------------------------

// / -----------------------------------------------------------------------------------
// / A function to toggle the visibility of an HTML element.
// / Switches the 'Visibility' property between 'block' & 'none'.
// / An element that is not on the page cannot be toggled. Most callers are inline onclick
// / attributes that cannot test for this themselves, so refusing quietly & naming the
// / element that was missing is the only outcome that does not throw into the console.
function toggle_visibility(id) {
  var e = document.getElementById(id);
  if (!e) {
    warningToConsole('Cannot toggle "' + id + '". No such element exists on this page.');
    return; }
  if (e.style.display == 'block') e.style.display = 'none';
  else e.style.display = 'block'; }
