// / -----------------------------------------------------------------------------------
// / A function to decide whether one line of a core reply names a file.
// / The core sanitizer strips < > / and every quote out of a filename before that filename
// / is ever written to disk, so a line carrying any of them is markup the core printed
// / around its answer rather than the answer itself. That covers the doctype the core
// / opens every reply with, & the line break it prints after every error message.
function line_is_filename(line) {
  line = String(line || '').trim();
  if (line === '') return false;
  if (line.indexOf('ERROR' + '!!!') !== -1) return false;
  if (line.indexOf('<') !== -1 || line.indexOf('>') !== -1) return false;
  return true; }
// / -----------------------------------------------------------------------------------

// / -----------------------------------------------------------------------------------
// / A function to decide whether a core reply reports a failure.
// / A core error arrives with an HTTP 200 & a body, so the request itself succeeds & the
// / success handler is the one that runs. The body is the only thing that separates a
// / failure from a success, which is why every caller must ask this before acting on one.
// / Two shapes count as a failure. A body carrying the error tag, & a body carrying one of
// / the alert strings the core prints WITHOUT a tag when it refuses an operation before
// / attempting it. Those strings are localized, so the calling page supplies them.
// / An empty body is NOT a failure. A successful download prints no filename at all.
// /
// / THE TAG IS ASSEMBLED, NEVER WRITTEN OUT WHOLE.
// / A page that searches a reply for a literal marker & also contains that literal in its
// / own source will match itself the moment a reply happens to carry a copy of the page.
// / That is not hypothetical. It happened, & every delete reported failure while
// / succeeding perfectly. Building the marker in two halves cannot do that.
function reply_is_error(replyText, failureStrings) {
  var text = String(replyText || '');
  var errorTag = 'ERROR' + '!!!';
  var lines = [];
  var line = '';
  var index = 0;
  if (text.indexOf(errorTag) !== -1) return true;
  if (!failureStrings || !failureStrings.length) return false;
  lines = text.split(/\r?\n/);
  for (index = 0; index < lines.length; index++) {
    line = lines[index].trim();
    if (line !== '' && failureStrings.indexOf(line) !== -1) return true; }
  return false; }
// / -----------------------------------------------------------------------------------

// / -----------------------------------------------------------------------------------
// / A function to point the hidden download anchor at a file & trigger it.
// / The filename is encoded because ? + and = all survive the core sanitizer.
// / The basePath carries the session separators & is never encoded.
// / This test is a backstop & is NOT a substitute for reply_is_error(). A caller that
// / already knows the filename it asked for passes this test with a name the core never
// / actually produced, which points the anchor at a file that does not exist.
// / This function reports whether it pointed the anchor at anything. Callers must consume
// / that answer, because a refusal here is a failed download.
function download_file(basePath, fileName) {
  var e = document.getElementById('downloadTarget');
  if (!e) {
    warningToConsole('Cannot download "' + fileName + '". The download anchor is missing from this page.');
    return false; }
  if (!line_is_filename(fileName)) {
    warningToConsole('Refused to download "' + fileName + '". That is not a filename.');
    return false; }
  e.href = basePath + encodeURIComponent(fileName);
  e.click();
  return true; }
// / -----------------------------------------------------------------------------------

// / -----------------------------------------------------------------------------------
// / A function to build a shareable absolute URL for a file without downloading it.
// / Used by the share link display & by the copy to clipboard routine.
// / The filename is encoded for the same reasons given in download_file().
// / A share link is copied as plain text & receives no browser normalization at all,
// / so encoding here is the only thing that makes a non ASCII share link work.
function share_file_url(baseURL, fileName) {
  return baseURL + encodeURIComponent(fileName); }
